// Writes script/picker/contents/ui/layouts.js: the thumbnail rectangles of the layout picker,
// as fractions of the work area (4 windows, 2560x1440 with small gaps).
// Run from anywhere: node core/tools/render-picker-data.js
const fs = require('node:fs');
const path = require('node:path');
const {tree, stage, scroll} = require('../index.js');

const AREA = {x: 0, y: 0, width: 2560, height: 1440};
const GAPS = {inner: 24, outer: 24};
const IDS = ['1', '2', '3', '4'];
const STAGE_PARAMS = {gaps: GAPS, focusRatio: 0.6, gradient: 0.5, railCellMin: {w: 140, h: 110}};

function fractions(rects) {
  const round = v => Math.round(v * 10000) / 10000;
  return IDS.filter(id => rects[id]).map(id => {
    const r = rects[id];
    return [round(r.x / AREA.width), round(r.y / AREA.height),
      round(r.width / AREA.width), round(r.height / AREA.height)];
  });
}

function build() {
  const layouts = tree.LAYOUTS.map(name => ({
    name,
    rects: fractions(tree.layout(tree.generate(name, IDS), AREA, GAPS)),
  }));
  layouts.push({
    name: 'stage',
    rects: fractions(stage.layout(stage.fromOrder(IDS), AREA, STAGE_PARAMS).rects),
  });
  layouts.push({name: 'scroll',
    rects: fractions(scroll.layout(IDS, scroll.create(), AREA, GAPS).rects)});
  return layouts;
}

function render() {
  const rows = build().map(l =>
    `    {name: "${l.name}", rects: [\n` +
    l.rects.map(r => `        [${r.join(', ')}],\n`).join('') + '    ]},\n').join('');
  return '// Generated by core/tools/render-picker-data.js: do not edit.\n' +
    '// Per layout, up to 4 visible windows as [x, y, width, height] fractions of the work area.\n' +
    '.pragma library\n\nvar layouts = [\n' + rows + '];\n';
}

const file = path.join(__dirname, '..', '..', 'script', 'picker', 'contents', 'ui', 'layouts.js');
if (require.main === module) {
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, render());
  console.log('wrote', file);
}
module.exports = {build, render, file};
